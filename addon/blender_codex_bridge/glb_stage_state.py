"""Pure bounded stage-intent/observation ledger, not native ownership authority.

No bpy, path reads, native constructors, cleanup, history or checkpoint work.
Future canonical domain code must independently prove grants, request lifetime,
native ownership and every recorded observation. Integers/digests accepted here
are data, never a Boolean or token that authorizes Blender actions.
"""
from __future__ import annotations

import hashlib
import json
import math
import re
import secrets
import time
from collections.abc import Callable
from dataclasses import dataclass, replace

from .asset_glb_import_plan import (
    GLBImportPlan,
    plan_glb,
    require_loss_acceptance,
    validate_conversion_requirements,
)
from .errors import invalid_argument
from .glb_stage_source import GLBSource

MAX_RECORDS = 16
MAX_RETAINED_BYTES = 32 * 1024**2
MAX_ALLOCATIONS = 81  # Collection +32Objects +16Meshes +16Materials +16embedded trees.
MAX_NATIVE_IDENTITY = 2**64 - 1
MAX_INSPECTION_BYTES = 32768
PREVIEW_SECONDS = 300


def _name(value: str) -> str:
    try:
        valid = (type(value) is str and bool(value.strip()) and len(value.encode("utf8")) <= 40
                 and not any(ord(c) < 32 or ord(c) == 127 for c in value))
    except UnicodeError:
        valid = False
    if not valid:
        raise invalid_argument("Stage collection name must be printable and within 40 UTF-8 bytes.")
    return value


def _digest(value: str) -> str:
    if type(value) is not str or re.fullmatch(r"[a-f0-9]{64}", value) is None:
        raise invalid_argument("Stage fingerprint must be exactly 64 lowercase hexadecimal characters.")
    return value


def _clock() -> float:
    value = time.monotonic()
    if type(value) not in (int, float) or not math.isfinite(value) or value < 0:
        raise invalid_argument("Stage clock is unavailable.")
    return value


@dataclass(frozen=True, slots=True)
class StageIntent:
    preview_id: str
    stage_id: str
    generation: str
    source: GLBSource
    plan: GLBImportPlan
    collection_name: str
    destination_fingerprint: str
    allocation_names: tuple[tuple[str, str], ...]
    expires_at: float
    accounted_bytes: int
    fingerprint: str
    checkpoint_fingerprint: str | None = None


@dataclass(frozen=True, slots=True)
class AllocationObservation:
    role: str
    name: str
    native_uid: int
    pointer: int


@dataclass(frozen=True, slots=True)
class PublicationIntent:
    preview_id: str
    generation: str
    stage_id: str
    destination_scene_name: str
    destination_fingerprint: str
    constructed_prefix: str
    expires_at: float
    fingerprint: str


@dataclass(frozen=True, slots=True)
class StageRecord:
    intent: StageIntent
    phase: str = "PREPARED"
    allocations: tuple[AllocationObservation, ...] = ()
    prefix_digest: str | None = None
    possible_mutation: bool = False
    publication_observed: bool = False
    outcome_unknown: bool = False
    reason: str | None = None
    prior_phase: str | None = None
    publication_intent: PublicationIntent | None = None


def _names(plan: GLBImportPlan, name: str) -> tuple[tuple[str, str], ...]:
    rows = [("collection", name)]
    rows.extend((f"mesh:{m.source_index}", f"{name}.M{m.source_index}") for m in plan.meshes)
    # Embedded material trees retain the stock constructor name: their ID.name
    # setter rejects IDs outside global Main. Equal names never identify owners.
    for index in range(len(plan.materials)):
        rows.extend(((f"material:{index}", f"{name}.P{index}"),
                     (f"node_tree:{index}", "Shader Nodetree")))
    rows.extend((f"object:{n.source_index}", f"{name}.O{n.source_index}") for n in plan.nodes)
    if len(rows) > MAX_ALLOCATIONS:
        raise invalid_argument("Stage allocation intent exceeds its fixed budget.")
    return tuple(rows)


def _fingerprint(intent: StageIntent) -> str:
    # Only ordinary values generated by the unchanged planner reach this stream.
    checkpoint = (None if intent.checkpoint_fingerprint is None
                  else _digest(intent.checkpoint_fingerprint))
    checkpoint_bytes = 0 if checkpoint is None else 64
    intent.source.validate()
    validate_conversion_requirements(intent.plan)
    plan_bytes = intent.plan.canonical_bytes()
    if (intent.plan.source_sha256 != intent.source.sha256
            or intent.plan.source_bytes != len(intent.source.payload)
            or hashlib.sha256(plan_bytes).hexdigest() != intent.plan.normalized_sha256
            or intent.accounted_bytes != intent.source.accounted_bytes + len(plan_bytes) + checkpoint_bytes
            or intent.allocation_names != _names(intent.plan, intent.collection_name)):
        raise invalid_argument("Retained stage plan/source/allocation intent changed.")
    value = {"preview_id": intent.preview_id, "stage_id": intent.stage_id,
             "generation": intent.generation, "source": intent.source.proof(),
             "source_ancestry": intent.source.ancestry,
             "plan_sha256": intent.plan.normalized_sha256,
             "collection_name": intent.collection_name,
             "destination_fingerprint": intent.destination_fingerprint,
             "allocation_names": intent.allocation_names, "expires_at": intent.expires_at,
             "accounted_bytes": intent.accounted_bytes}
    # Preserve the original private-constructor seal when no runtime checkpoint
    # witness is supplied. The destination remains its separate environment CAS.
    if checkpoint is not None:
        value["checkpoint_fingerprint"] = checkpoint
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(",", ":"),
                                     allow_nan=False).encode()).hexdigest()


class GLBStageStore:
    """Session-local pure records; native IDs must live in a separate owned driver.

    Capacity accounts source payload/metadata, canonical-plan bytes and an
    optional 64-byte checkpoint digest, not Python object overhead/RSS. Numeric
    cardinality is separately bounded by plan_glb.
    No record is silently evicted, including unknown or stale partial stages.
    """

    def __init__(self) -> None:
        self._generation = secrets.token_hex(32)
        self._records: dict[str, StageRecord] = {}
        self._previews: dict[str, str] = {}
        self._active: str | None = None
        self._retained_bytes = 0

    @property
    def generation(self) -> str:
        return self._generation

    @property
    def retained_bytes(self) -> int:
        return self._retained_bytes

    def prepare(self, source: GLBSource, collection_name: str, destination_fingerprint: str,
                *, overwrite_policy: str, check: Callable[[], None] = lambda: None,
                checkpoint_fingerprint: str | None = None) -> StageRecord:
        if type(source) is not GLBSource:
            raise invalid_argument("Stage source must be an exact independently read snapshot.")
        source.validate()
        name, destination = _name(collection_name), _digest(destination_fingerprint)
        checkpoint = (None if checkpoint_fingerprint is None
                      else _digest(checkpoint_fingerprint))
        if type(overwrite_policy) is not str or overwrite_policy != "REFUSE":
            raise invalid_argument("Stage creation only admits explicit REFUSE overwrite policy.")
        if len(self._records) >= MAX_RECORDS:
            raise invalid_argument("Stage record capacity reached; retained effects were not evicted.")
        generation, records, previews = self._generation, self._records, self._previews
        source_facts = (source.path, source.approved_root, source.ancestry,
                        source.file_identity, source.payload, source.sha256)
        plan = plan_glb(source.payload, check)
        if (self._generation != generation or self._records is not records
                or self._previews is not previews):
            raise invalid_argument("Stage session/store identity changed during numeric planning.")
        if source_facts != (source.path, source.approved_root, source.ancestry,
                            source.file_identity, source.payload, source.sha256):
            raise invalid_argument("Stage source changed during numeric planning.")
        validate_conversion_requirements(plan)
        accounted = source.accounted_bytes + len(plan.canonical_bytes()) + (0 if checkpoint is None else 64)
        if self._retained_bytes + accounted > MAX_RETAINED_BYTES:
            raise invalid_argument("Retained source/plan byte budget reached; no partial effects were evicted.")
        preview, stage = "glb_preview_" + secrets.token_hex(16), "glb_stage_" + secrets.token_hex(16)
        if preview in self._previews or stage in self._records:
            raise invalid_argument("Stage token collision; existing records remain unchanged.")
        intent = StageIntent(preview, stage, generation, source, plan, name, destination,
                             _names(plan, name), _clock() + PREVIEW_SECONDS, accounted, "", checkpoint)
        intent = replace(intent, fingerprint=_fingerprint(intent))
        record = StageRecord(intent)
        # A caller receives this sealed stage lookup before any future constructor.
        if len(self._records) >= MAX_RECORDS:
            raise invalid_argument("Stage record capacity changed during numeric planning.")
        self._records[stage], self._previews[preview] = record, stage
        self._retained_bytes += accounted
        return record

    def lookup(self, stage_id: str) -> StageRecord:
        if type(stage_id) is not str or re.fullmatch(r"glb_stage_[a-f0-9]{32}", stage_id) is None:
            raise invalid_argument("An exact retained stage_id is required.")
        try:
            return self._records[stage_id]
        except KeyError as cause:
            raise invalid_argument("Unknown stage; no same-name native lookup or adoption is performed.") from cause

    def begin(self, preview_id: str, expected_fingerprint: str,
              accepted_losses: list[str]) -> StageRecord:
        if type(preview_id) is not str or preview_id not in self._previews:
            raise invalid_argument("An exact retained preview_id is required.")
        record = self.lookup(self._previews[preview_id])
        intent = record.intent
        if (record.phase != "PREPARED" or intent.generation != self._generation
                or _clock() >= intent.expires_at or self._active is not None):
            raise invalid_argument("Stage preview is stale, consumed or another creation is active.")
        if _digest(expected_fingerprint) != intent.fingerprint or _fingerprint(intent) != intent.fingerprint:
            raise invalid_argument("Stage source/destination intent fingerprint changed.")
        require_loss_acceptance(intent.plan, accepted_losses)
        record = replace(record, phase="ALLOCATING", possible_mutation=True)
        self._records[intent.stage_id], self._active = record, intent.stage_id
        return record

    def _writing(self, stage_id: str) -> StageRecord:
        record = self.lookup(stage_id)
        if (self._active != stage_id or record.phase not in {"ALLOCATING", "PUBLISHING"}
                or record.intent.generation != self._generation
                or _fingerprint(record.intent) != record.intent.fingerprint):
            raise invalid_argument("Stage observation owner/intent is no longer active.")
        return record

    def note_allocation(self, stage_id: str, role: str, name: str,
                        native_uid: int, pointer: int) -> StageRecord:
        """Record primitive observations only; this cannot prove native ownership."""
        record = self._writing(stage_id)
        if (type(role) is not str or type(name) is not str
                or (role, name) not in record.intent.allocation_names
                or type(native_uid) is not int or not 0 < native_uid <= MAX_NATIVE_IDENTITY
                or type(pointer) is not int or not 0 < pointer <= MAX_NATIVE_IDENTITY
                or any(row.role == role for row in record.allocations)):
            raise invalid_argument("Allocation observation differs from exact stage intent.")
        if any(row.native_uid == native_uid or row.pointer == pointer
               for retained in self._records.values() for row in retained.allocations):
            raise invalid_argument("Allocation identity is already observed; replacement/adoption is refused.")
        record = replace(record, prefix_digest=None, allocations=(*record.allocations,
                         AllocationObservation(role, name, native_uid, pointer)))
        self._records[stage_id] = record
        return record

    def note_prefix(self, stage_id: str, prefix_digest: str) -> StageRecord:
        record = self._writing(stage_id)
        record = replace(record, prefix_digest=_digest(prefix_digest))
        self._records[stage_id] = record
        return record

    def finish(self, stage_id: str, *, published: bool) -> StageRecord:
        """Record a trusted future driver's observation, never perform publication."""
        record = self._writing(stage_id)
        if (type(published) is not bool or record.prefix_digest is None
                or len(record.allocations) != len(record.intent.allocation_names)):
            raise invalid_argument("Complete expected-ID observations and a prefix digest are required.")
        record = replace(record, phase="PUBLISHED" if published else "CONSTRUCTED",
                         publication_observed=published)
        self._records[stage_id], self._active = record, None
        return record

    def fail(self, stage_id: str, reason: str, *, outcome_unknown: bool) -> StageRecord:
        record = self.lookup(stage_id)
        if record.phase not in {"PREPARED", "ALLOCATING", "PUBLISHING"} or type(outcome_unknown) is not bool:
            raise invalid_argument("Only pending/active stages can record a terminal failure once.")
        if (type(reason) is not str or re.fullmatch(r"[A-Z][A-Z0-9_]{0,63}", reason) is None):
            raise invalid_argument("Stage failure requires a bounded primitive reason code.")
        record = replace(record, phase="UNKNOWN" if outcome_unknown else "FAILED",
                         outcome_unknown=outcome_unknown, reason=reason)
        self._records[stage_id] = record
        if self._active == stage_id:
            self._active = None
        return record

    def prepare_publication(self, stage_id: str, destination_scene_name: str,
                            destination_fingerprint: str, *, overwrite_policy: str) -> PublicationIntent:
        record = self.lookup(stage_id)
        if (record.phase != "CONSTRUCTED" or record.intent.generation != self._generation
                or record.prefix_digest is None or self._active is not None
                or overwrite_policy != "REFUSE"):
            raise invalid_argument("Only an exact current constructed stage can preview publication.")
        destination = _digest(destination_fingerprint)
        name = _name(destination_scene_name)
        preview = "glb_publish_" + secrets.token_hex(16)
        expires = _clock() + PREVIEW_SECONDS
        values = (preview, self._generation, stage_id, name, destination, record.prefix_digest, expires)
        fingerprint = hashlib.sha256(json.dumps(values, separators=(",", ":"), allow_nan=False).encode()).hexdigest()
        intent = PublicationIntent(*values, fingerprint)
        self._records[stage_id] = replace(record, publication_intent=intent)
        return intent

    def begin_publication(self, stage_id: str, preview_id: str, expected_fingerprint: str,
                          *, overwrite_policy: str) -> StageRecord:
        record = self.lookup(stage_id)
        intent = record.publication_intent
        if (record.phase != "CONSTRUCTED" or intent is None or self._active is not None
                or intent.generation != self._generation or record.intent.generation != self._generation
                or intent.stage_id != stage_id or intent.preview_id != preview_id
                or _clock() >= intent.expires_at or overwrite_policy != "REFUSE"
                or _digest(expected_fingerprint) != intent.fingerprint
                or record.prefix_digest != intent.constructed_prefix):
            raise invalid_argument("Publication preview is missing, stale, replaced or consumed.")
        values = (intent.preview_id, intent.generation, intent.stage_id, intent.destination_scene_name,
                  intent.destination_fingerprint, intent.constructed_prefix, intent.expires_at)
        if hashlib.sha256(json.dumps(values, separators=(",", ":"), allow_nan=False).encode()).hexdigest() != intent.fingerprint:
            raise invalid_argument("Publication intent changed.")
        record = replace(record, phase="PUBLISHING", possible_mutation=True)
        self._records[stage_id], self._active = record, stage_id
        return record

    def finish_publication(self, stage_id: str, prefix_digest: str) -> StageRecord:
        record = self._writing(stage_id)
        if record.phase != "PUBLISHING" or record.publication_intent is None:
            raise invalid_argument("No active publication observation owner exists.")
        record = replace(record, phase="PUBLISHED", prefix_digest=_digest(prefix_digest),
                         publication_observed=True)
        self._records[stage_id], self._active = record, None
        return record

    def mark_unknown(self, stage_id: str, reason: str) -> StageRecord:
        """Pure recovery status, including failure of a trailing checkpoint."""
        record = self.lookup(stage_id)
        if record.phase == "STALE":
            return record
        if type(reason) is not str or re.fullmatch(r"[A-Z][A-Z0-9_]{0,63}", reason) is None:
            raise invalid_argument("Unknown outcome requires a bounded reason code.")
        record = replace(record, phase="UNKNOWN", outcome_unknown=True,
                         possible_mutation=True, reason=reason, prior_phase=record.prior_phase or record.phase)
        self._records[stage_id] = record
        if self._active == stage_id:
            self._active = None
        return record

    def invalidate(self) -> None:
        """Invalidate write authority; keep every record/partial observation intact."""
        self._generation = secrets.token_hex(32)
        for identifier, record in tuple(self._records.items()):
            self._records[identifier] = replace(record, phase="STALE",
                outcome_unknown=record.outcome_unknown or record.possible_mutation,
                reason=record.reason or "SESSION_INVALIDATED",
                prior_phase=record.prior_phase or record.phase)
        self._active = None

    def inspect(self, stage_id: str) -> dict:
        """Read-only primitive evidence, with no native-current-state assurance."""
        record = self.lookup(stage_id)
        result = {"stage_id": stage_id, "preview_id": record.intent.preview_id,
                "phase": record.phase, "collection_name": record.intent.collection_name,
                "prior_phase": record.prior_phase,
                "session_valid": record.intent.generation == self._generation,
                "possible_mutation": record.possible_mutation,
                "publication_observed": record.publication_observed,
                "outcome_unknown": record.outcome_unknown, "reason": record.reason,
                "prefix_digest": record.prefix_digest,
                "observed_allocations": [{"role": a.role, "name": a.name,
                    "native_uid": a.native_uid, "pointer": a.pointer} for a in record.allocations],
                "expected_id_observations_complete": len(record.allocations) == len(record.intent.allocation_names),
                "native_ownership_verified": False, "native_allocation_inventory_verified": False,
                "live_request_or_permission_verified": False, "project_saved": False,
                "durable_recovery_verified": False, "source_read_performed": False}
        if len(json.dumps(result, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()) > MAX_INSPECTION_BYTES:
            raise invalid_argument("Stage inspection exceeds its fixed byte budget.")
        return result
